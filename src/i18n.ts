const dicts: Record<Lang, Record<Key, string>> = { tr, en }

export const defaultLang = (): Lang => {
  try {
    return navigator.language?.toLowerCase().startsWith('tr') ? 'tr' : 'en'
  } catch {
    return 'en'
  }
}

export function translate(lang: Lang, key: Key, params?: Record<string, string | number>): string {
  let text = dicts[lang][key] ?? key
  if (params) for (const [k, v] of Object.entries(params)) text = text.replace(`{${k}}`, String(v))
  return text
}
